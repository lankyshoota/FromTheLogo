/* Writes supabase/packs.sql: the daily pack for every date from LAUNCH through a year from now,
 * built by prompts.js from players.json exactly as the game builds it. The server only hands out
 * these stored packs (get_or_create_pack no longer accepts a pack from the browser).
 *
 *   node make_packs.js            # LAUNCH .. today + 365 days
 *   node make_packs.js 730        # .. today + 730 days
 *
 * Dates are Eastern calendar dates (the game's day runs midnight to midnight ET), so each row is
 * the pack for that ET date. Then paste supabase/packs.sql into the Supabase SQL editor. Re-running it replaces packs for
 * dates nobody has played yet and never touches a date that already has picks. Re-run it after
 * players.json changes if you want future packs to use the new data (e.g. award prompts), and
 * before the schedule runs out (the admin page shows the last scheduled date).
 */
const fs = require('fs');
const path = require('path');
const R = require('./rarity.js');
const F = require('./prompts.js');

const players = JSON.parse(fs.readFileSync(path.join(__dirname, 'players.json')));
const G = F.create(players, { rarity: R.create(players) });
const ahead = Number(process.argv[2]) || 365;
const first = new Date('2026-10-22T00:00:00Z');   // prompts.js LAUNCH
const last = new Date(Date.now() + ahead * 864e5);

const q = s => "'" + s.replace(/'/g, "''") + "'";
const rows = [];
for (let d = first; d <= last; d = new Date(d.getTime() + 864e5)) {
  const key = d.toISOString().slice(0, 10);
  const pack = G.daily(key).map(id => ({ id, text: G.get(id).text }));
  if (pack.length !== F.PACK_SIZE) throw new Error(`${key}: ${pack.length} prompts`);
  rows.push(`  (${q(key)}, ${q(JSON.stringify(pack))}::jsonb)`);
}
const out = `-- FromTheLogo daily packs, ${rows.length} days (${first.toISOString().slice(0, 10)} to ${last.toISOString().slice(0, 10)}).
-- Generated by make_packs.js from players.json (${players.length} players). Paste into Supabase:
-- SQL Editor -> New query -> Run. Safe to re-run: dates that already have picks keep their pack.
insert into daily_packs (pack_date, prompts) values
${rows.join(',\n')}
on conflict (pack_date) do update set prompts = excluded.prompts
where not exists (select 1 from picks p where p.pack_date = daily_packs.pack_date);
`;
fs.writeFileSync(path.join(__dirname, 'supabase', 'packs.sql'), out);
console.log(`supabase/packs.sql: ${rows.length} packs, through ${last.toISOString().slice(0, 10)} (${(out.length / 1024).toFixed(0)} KB)`);
